"""Generate the frozen test suite: edge cases around every threshold, plus seeded realistic profiles.

Expected values come from the independent oracle. Output is committed to tests/cases/ and never
regenerated by an implementation, so a bug in an implementation cannot change what it is tested against.

Run: python -m project_a.tests.gen_cases
"""
from __future__ import annotations

import json
import random
from pathlib import Path

from project_a.tests.golden import _inp
from project_a.tests.oracle import compute

OUT = Path(__file__).parent / "cases"
DELTAS = (-10, -5, -4, 0, 4, 5, 10, 100)
OLD_STD, NEW_STD = 50000, 75000
NEW_SLABS = {"2024-25": (300000, 700000, 1000000, 1200000, 1500000), "2025-26": (400000, 800000, 1200000, 1600000, 2000000, 2400000)}
REBATE_LIMIT = {"2024-25": 700000, "2025-26": 1200000}
SURCHARGE_BANDS = (5000000, 10000000, 20000000, 50000000)


def _relief_end(fy: str, regime: str, threshold: int, age: int = 30) -> int:
    """Bisect for the first total income above `threshold` whose surcharge relief has run out."""
    std = OLD_STD if regime == "old" else NEW_STD

    def in_relief(ti: int) -> bool:
        res = compute(_inp(fy=fy, age=age, gross=ti + std))[regime]
        rate = 0.37 if (regime == "old" and ti > 50000000) else 0.25 if ti > 20000000 else 0.15 if ti > 10000000 else 0.10
        return res["surcharge"] < round(res["slab_tax"] * rate, 2)

    low, high = threshold + 10, threshold + 3000000
    if not in_relief(low):
        return low
    while high - low > 10:
        mid = (low + high) // 2 // 10 * 10
        if mid in (low, high):
            break
        low, high = (mid, high) if in_relief(mid) else (low, mid)
    return high


def build_cases(fy: str) -> list[dict]:
    cases: list[dict] = []

    def add(category: str, label: str, inp: dict) -> None:
        cases.append({"id": f"{fy}-{category}-{label}", "category": category, "input": inp})

    # 1. Every slab boundary, regime and age band, approached from both sides including 288A rounding.
    for age, bounds in ((30, (250000, 500000, 1000000)), (60, (300000, 500000, 1000000)), (80, (500000, 1000000))):
        for bound in bounds:
            for d in DELTAS:
                add("old_slab", f"age{age}_{bound}_{d:+d}", _inp(fy=fy, age=age, gross=bound + d + OLD_STD))
    for bound in NEW_SLABS[fy]:
        for d in DELTAS:
            add("new_slab", f"{bound}_{d:+d}", _inp(fy=fy, gross=bound + d + NEW_STD))

    # 2. Age band edges.
    for age in (59, 60, 61, 79, 80, 81):
        add("age_edge", f"age{age}", _inp(fy=fy, age=age, gross=900000))

    # 3. Section 87A: limit and the far end of new-regime marginal relief.
    limit = REBATE_LIMIT[fy]
    breakeven = 722222 if fy == "2024-25" else 1270588
    for d in (-100, -10, 10, 50, 100, 1000, 10000):
        add("rebate_old", f"{d:+d}", _inp(fy=fy, gross=500000 + d + OLD_STD))
        add("rebate_new", f"{d:+d}", _inp(fy=fy, gross=limit + d + NEW_STD))
    for d in (-100, -10, 0, 10, 100):
        add("rebate_new_breakeven", f"{d:+d}", _inp(fy=fy, gross=breakeven + d + NEW_STD))

    # 4. Surcharge bands and marginal relief, both regimes, including where relief runs out.
    for regime, std in (("old", OLD_STD), ("new", NEW_STD)):
        for bound in SURCHARGE_BANDS:
            for d in (-10, 0, 10, 1000, 100000):
                add("surcharge", f"{regime}_{bound}_{d:+d}", _inp(fy=fy, gross=bound + d + std))
            end = _relief_end(fy, regime, bound)
            for d in (-10, 0, 10):
                add("surcharge_relief_end", f"{regime}_{bound}_{d:+d}", _inp(fy=fy, gross=end + d + std))
    for age in (60, 80):
        add("surcharge_age", f"age{age}", _inp(fy=fy, age=age, gross=5100000))

    # 5. Deduction caps on each side of the limit.
    gross = 1500000
    for amt in (149999, 150000, 150001, 300000):
        add("cap_80c", str(amt), _inp(fy=fy, gross=gross, sec_80c=amt))
    for amt in (49999, 50000, 50001, 100000):
        add("cap_80ccd1b", str(amt), _inp(fy=fy, gross=gross, sec_80ccd1b=amt))
    for age in (59, 60):
        for amt in (24999, 25000, 25001, 49999, 50000, 50001):
            add("cap_80d_self", f"age{age}_{amt}", _inp(fy=fy, age=age, gross=gross, sec_80d_self=amt))
    for senior in (False, True):
        for amt in (24999, 25000, 25001, 50000, 50001):
            add("cap_80d_parents", f"senior{senior}_{amt}", _inp(fy=fy, gross=gross, sec_80d_parents=amt, parents_senior=senior))
    for amt in (199999, 200000, 200001, 500000):
        add("cap_home_loan", str(amt), _inp(fy=fy, gross=gross, home_loan_interest=amt))

    # 6. HRA: each branch of "least of three", metro and non-metro, rent below 10%, odd rupee salaries.
    hra_cases = [
        ("actual_least", 600000, 100000, 300000, True),
        ("rent_least", 600000, 300000, 200000, True),
        ("pct_least_metro", 400000, 300000, 600000, True),
        ("pct_least_nonmetro", 400000, 300000, 600000, False),
        ("rent_below_10pct", 600000, 200000, 50000, True),
        ("rent_at_10pct", 600000, 200000, 60000, True),
        ("no_rent", 600000, 200000, 0, False),
        ("no_hra", 600000, 0, 240000, True),
        ("odd_salary", 612345, 245678, 180005, False),
        ("odd_salary_metro", 987654, 493827, 400009, True),
        ("rent_equals_tie", 500000, 250000, 300000, True),
        ("high_earner", 4000000, 2000000, 2500000, True),
    ]
    for label, basic, hra, rent, metro in hra_cases:
        add("hra", label, _inp(fy=fy, basic_da=basic, hra_received=hra, rent_paid=rent, metro=metro, other_salary=100000))

    # 7. Income too low to absorb deductions.
    for g in (0, 1, 30000, 49999, 50000, 50001, 75000, 75001, 200000):
        add("low_income", str(g), _inp(fy=fy, gross=g))
    add("deductions_exceed_income", "all", _inp(fy=fy, gross=400000, sec_80c=150000, sec_80ccd1b=50000, sec_80d_self=25000, home_loan_interest=200000))
    add("deductions_exceed_income", "loss_exceeds_salary", _inp(fy=fy, gross=150000, home_loan_interest=200000))

    # 8. Stacked deductions, where regime choice is a real decision.
    for g in (800000, 1000000, 1250000, 1500000, 1800000, 2400000, 3000000, 6000000):
        add(
            "stacked",
            str(g),
            _inp(fy=fy, age=45, gross=g, sec_80c=150000, sec_80ccd1b=50000, sec_80d_self=25000, sec_80d_parents=50000, parents_senior=True, home_loan_interest=200000),
        )

    # 9. Seeded realistic profiles.
    rng = random.Random(f"fireai-{fy}")
    for n in range(50):
        basic = rng.randrange(300000, 3000000, 1000)
        hra = rng.choice((0, basic * 2 // 5, basic // 2))
        add(
            "profile",
            str(n),
            _inp(
                fy=fy,
                age=rng.choice((24, 28, 33, 38, 44, 52, 58, 60, 66, 72, 79, 80, 85)),
                basic_da=basic,
                hra_received=hra,
                other_salary=rng.randrange(0, 800000, 500),
                rent_paid=rng.choice((0, 120000, 240000, 360000, 600000)) if hra else 0,
                metro=rng.random() < 0.5,
                sec_80c=rng.choice((0, 50000, 100000, 150000, 200000)),
                sec_80ccd1b=rng.choice((0, 0, 25000, 50000, 75000)),
                sec_80d_self=rng.choice((0, 12000, 25000, 40000, 60000)),
                sec_80d_parents=rng.choice((0, 0, 20000, 30000, 60000)),
                parents_senior=rng.random() < 0.5,
                home_loan_interest=rng.choice((0, 0, 100000, 200000, 350000)),
            ),
        )

    seen: set[str] = set()
    unique = []
    for case in cases:
        fingerprint = json.dumps(case["input"], sort_keys=True)
        if fingerprint not in seen:
            seen.add(fingerprint)
            case["expected"] = compute(case["input"])
            unique.append(case)
    return unique


def main() -> None:
    OUT.mkdir(exist_ok=True)
    for fy in ("2024-25", "2025-26"):
        cases = build_cases(fy)
        (OUT / f"fy{fy.replace('-', '_')}.json").write_text(json.dumps(cases, indent=1) + "\n")
        print(fy, len(cases))


if __name__ == "__main__":
    main()
